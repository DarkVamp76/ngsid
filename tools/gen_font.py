#!/usr/bin/env python3
"""Bake DejaVu Sans (Latin-1) into gui/font_data.h: an 8 bit alpha atlas plus glyph metrics.
Usage: python3 tools/gen_font.py /path/to/DejaVuSans.ttf > gui/font_data.h
DejaVu fonts are under the free Bitstream Vera / DejaVu license, which allows embedding."""
import sys
from PIL import Image, ImageDraw, ImageFont
PX = 32
W = 512
font = ImageFont.truetype(sys.argv[1], PX)
asc, desc = font.getmetrics()
codes = list(range(32, 127)) + list(range(160, 256))
glyphs = []
x = y = 1
rowh = 0
placed = []
for cp in codes:
    ch = chr(cp)
    adv = font.getlength(ch)
    l, t, r, b = font.getbbox(ch)
    w, h = max(r - l, 0), max(b - t, 0)
    if x + w + 2 > W:
        x = 1; y += rowh + 2; rowh = 0
    placed.append((cp, x, y, w, h, l, t, adv))
    x += w + 2; rowh = max(rowh, h)
H = 1
while H < y + rowh + 2: H *= 2
img = Image.new("L", (W, H), 0)
d = ImageDraw.Draw(img)
for cp, gx, gy, w, h, l, t, adv in placed:
    d.text((gx - l, gy - t), chr(cp), font=font, fill=255)
print("/* generated by tools/gen_font.py from DejaVu Sans, do not edit */")
print("#define FONT_PX %d\n#define FONT_ATLAS_W %d\n#define FONT_ATLAS_H %d\n#define FONT_ASCENT %d\n#define FONT_DESCENT %d" % (PX, W, H, asc, desc))
print("typedef struct { unsigned short code, x, y, w, h; short xoff, yoff; float adv; } font_glyph;")
print("static const font_glyph font_glyphs[] = {")
for cp, gx, gy, w, h, l, t, adv in placed:
    print("  {%d,%d,%d,%d,%d,%d,%d,%.3ff}," % (cp, gx, gy, w, h, l, t, adv))
print("};\n#define FONT_GLYPH_COUNT %d" % len(placed))
data = img.tobytes()
print("static const unsigned char font_atlas[%d] = {" % len(data))
for i in range(0, len(data), 32):
    print(",".join(str(v) for v in data[i:i+32]) + ",")
print("};")
